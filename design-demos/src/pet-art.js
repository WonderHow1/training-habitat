function pixelSprite(art) {
  const pixels = art.trim().split('\n').map(row => row.trim());
  const width = Math.max(...pixels.map(row => row.length));
  return { pixels: pixels.map(row => row.padEnd(width, '.')), width };
}

function petArt(colors, scarf, art) {
  return {
    ...pixelSprite(art),
    scarf,
    colors: { W: '#fff5df', M: colors.I, E: colors.I, ...colors }
  };
}

